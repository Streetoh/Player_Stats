with open("js/player-app.js", "r", encoding="utf-8") as f:
    content = f.read()

# Replace Spanish values inside ru: { ... } block
ru_match = re.search(r"(\n\s+ru:\s*\{)([\s\S]*?)(\n\s+\}\s*,\s*\n\s+es:)", content)
if not ru_match:
    # Try finding ru at end of DICT
    ru_match = re.search(r"(\n\s+ru:\s*\{)([\s\S]*?)(\n\s+\}\s*;\s*\n\s+DICT\.et)", content)

if ru_match:
    prefix = ru_match.group(1)
    ru_block = ru_match.group(2)
    suffix = ru_match.group(3)

    for k, v in RU_TRANSLATIONS.items():
        pattern = rf'\"{k}\"\s*:\s*\"[^\"]*\"'
        replacement = f'"{k}": "{v}"'
        if re.search(pattern, ru_block):
            ru_block = re.sub(pattern, replacement, ru_block)
        else:
            # If key wasn't in ru block, append it
            ru_block += f',\n      "{k}": "{v}"'

    content = content[:ru_match.start()] + prefix + ru_block + suffix + content[ru_match.end():]
    print("Successfully replaced RU translations in js/player-app.js")
else:
    print("Could not find RU block in js/player-app.js")

with open("js/player-app.js", "w", encoding="utf-8") as f:
    f.write(content)

print("Saved player-app.js successfully!")
